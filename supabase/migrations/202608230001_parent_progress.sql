-- Shared family-learning schema. It supports this NMG app and future subjects/apps.
create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.families (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now()
);

create table if not exists public.family_members (
  family_id uuid not null references public.families(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('parent')),
  created_at timestamptz not null default now(),
  primary key (family_id, user_id)
);

create table if not exists public.learners (
  id uuid primary key default gen_random_uuid(),
  family_id uuid not null references public.families(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 1 and 40),
  created_at timestamptz not null default now()
);

-- Every future learning application registers one reusable catalogue row.
create table if not exists public.learning_apps (
  app_key text primary key check (app_key ~ '^[a-z0-9][a-z0-9-]{2,79}$'),
  title text not null check (char_length(title) between 1 and 120),
  subject text not null check (char_length(subject) between 1 and 60),
  grade_label text check (char_length(grade_label) <= 60),
  topic_labels jsonb not null default '[]'::jsonb check (jsonb_typeof(topic_labels) = 'array'),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

