-- Each browser/app installation is an anonymous Supabase user linked to David.
create table if not exists public.learner_devices (
  learner_id uuid not null references public.learners(id) on delete cascade,
  device_user_id uuid not null references auth.users(id) on delete cascade,
  linked_at timestamptz not null default now(),
  primary key (learner_id, device_user_id),
  unique (device_user_id)
);

create table if not exists public.pairing_codes (
  id uuid primary key default gen_random_uuid(),
  learner_id uuid not null references public.learners(id) on delete cascade,
  code_hash text not null unique,
  expires_at timestamptz not null,
  claimed_at timestamptz,
  created_at timestamptz not null default now()
);

-- One baseline per app/device imports progress collected before cloud pairing.
create table if not exists public.legacy_progress (
  learner_id uuid not null references public.learners(id) on delete cascade,
  device_user_id uuid not null references auth.users(id) on delete cascade,
  app_key text not null references public.learning_apps(app_key),
  snapshot jsonb not null check (jsonb_typeof(snapshot) = 'object'),
  imported_at timestamptz not null default now(),
  primary key (learner_id, device_user_id, app_key)
);

-- Generic event model: score supports binary or partial credit in future apps.
create table if not exists public.learning_events (
  id bigint generated by default as identity primary key,
  client_event_id uuid not null unique,
  learner_id uuid not null references public.learners(id) on delete cascade,
  device_user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  app_key text not null references public.learning_apps(app_key),
  item_key text not null check (char_length(item_key) between 1 and 80),
  topic text not null check (char_length(topic) between 1 and 100),
  score numeric(5,4) not null check (score between 0 and 1),
  reward_points smallint not null default 0 check (reward_points between 0 and 100),
  duration_seconds integer check (duration_seconds between 0 and 86400),
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  occurred_at timestamptz not null,
  received_at timestamptz not null default now()
);

create index if not exists learning_events_learner_app_time_idx on public.learning_events (learner_id, app_key, occurred_at desc);
create index if not exists learning_events_learner_topic_idx on public.learning_events (learner_id, app_key, topic);
create index if not exists pairing_codes_expiry_idx on public.pairing_codes (expires_at) where claimed_at is null;

